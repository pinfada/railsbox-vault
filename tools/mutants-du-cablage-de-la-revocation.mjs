// La TABLE des mutants du CÂBLAGE de la révocation (#265, ADR 0049 § C2), concaténée par la campagne
// `coquille` (`tools/muter-gardes-coquille.mjs`). Elle ne mute pas le modèle d'état (C1 a la sienne) : elle
// mute ce que C2 y a branché — le rendeur unique, l'affichage, la construction de la vue, le câblage, la
// décision d'écran, les textes, `modifierEtAttendre`.
//
// Chaque mutant RETIRE ou INVERSE une garde ; `avant` apparaît UNE fois dans le fichier. Les identifiants
// M3xx sont ceux de la table de correspondance de la conception (#310, § X3 et R12).
//
// Ne sont PAS comptés, car ÉQUIVALENTS au comportement actuel, et dits plutôt que tus :
//  - M336/M337 (libération et successeur hors du `finally` de `regler`) : toute levée possible dans le
//    bloc est avalée par le `try` et le repli, et `noter` avale celles du journal ; rien n'atteint donc
//    le `finally` que le chemin nominal n'atteigne aussi. Le `finally` reste, par défense en profondeur ;
//  - M345 (`derniereOccurrenceTraitee` posée avant le `try`) : `clore` la repose, et `converger` ne fait
//    rien tant que `enVol` n'est pas libéré ;
//  - `lectures.delete(lecture)` (hygiène) : une lecture n'est plus lue après son acceptation ;
//  - `ctx.abonnes.delete(verifier)` dans `attendre` : le prédicat ne se réarme pas, rendre deux fois une
//    promesse déjà réglée ne change rien.

