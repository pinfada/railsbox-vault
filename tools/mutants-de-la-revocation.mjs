// La TABLE des mutants du modèle de la révocation (#310, ADR 0049), concaténée par la campagne
// `coquille` (`tools/muter-gardes-coquille.mjs`). Séparée parce que cette campagne fait déjà plus de
// 1 300 lignes ; aucune nouvelle campagne, aucun nouveau seuil.
//
// Chaque mutant RETIRE ou INVERSE exactement une garde ; `avant` apparaît UNE fois dans le fichier.
// Ne sont PAS comptés, car équivalents au comportement actuel : la comparaison de `donnees` et celle
// de `session.moyen` dans `occurrenceSuivante` (toute arête qui change l'instantané ou le moyen change
// aussi la phase) ; dans la fermeture, `!ctx.termine` et `ctx.etat === cible` de `transitionIntacte`,
// `!ctx.termine` de `masquerVerifie`, le test `ctx.termine` de `renoncer` et la renonciation de `envoyer`
// (la réentrance étant refusée, `terminer()` ne s'exécute jamais pendant une transition et aucun exécuteur
// ne s'exécute entre l'affectation de V et `envoyer`) ; la garde `etat.lecture !== null` de `classeDeLaLecture` (un identifiant entier
// n'égale jamais `null`) ; la garde `descripteur === undefined` de `resoudreLesExecuteurs` (lire `.value` d'`undefined`
// lève la même TypeError) ; les cellules « lecture courante » des phases sans lecture (inatteignables).

